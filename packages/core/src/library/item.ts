import type { SoundPackId } from "../schema";
import type { LibrarySnapshot } from "./snapshot";

/**
 * THE LIBRARY MODEL — one shape for every browsable thing in the app.
 *
 * Before this, "library" meant five things at once: a tab of text templates, a
 * tab of media assets, a tab of saved components, a tab of starred ids, and the
 * sound picker's catalogue. Five browsers, five card designs, five search
 * boxes, five ideas of what a preview is — and no way at all to browse content
 * that has not been downloaded yet, because every one of them assumed its
 * subject was already in the document.
 *
 * This collapses that into three orthogonal questions, and the whole system
 * falls out of keeping them apart:
 *
 *   `kind`     WHICH SHELF it sits on — the browse category.
 *   `action`   WHAT USING IT DOES — the edit it hands the editor.
 *   `preview`  WHAT IT LOOKS LIKE BEFORE you use it.
 *
 * They are separate because they genuinely vary independently: two shelves can
 * produce the same edit (a component and a media asset both place clips), one
 * shelf can produce two (a sound is a voice here and an audio clip there), and
 * a preview is a property of *how much you have downloaded*, not of either.
 * Conflating them is exactly what made the old tabs unbrowsable.
 *
 * The load-bearing rule about previews:
 *
 *   **A preview stands in for what the app cannot yet render itself.**
 *
 * Once an item's payload is local, the app draws the real thing with the real
 * renderer (`preview: { type: "render" }`) — the same pixels the canvas draws,
 * because it IS the canvas code. A published poster or loop only ever covers
 * the window between seeing a card and owning its bytes. That is why previews
 * are generated by the EDITOR at publish time and not by a headless browser in
 * CI: the thing that knows what a preset looks like is the renderer, and a
 * second implementation of it is a preview that lies.
 */

/* -------------------------------------------------------------------------- */
/* Shelves                                                                     */
/* -------------------------------------------------------------------------- */

/**
 * The browse categories. A new one is an arm here plus a provider — never a new
 * panel, a new card or a new search box.
 */
export const LIBRARY_KINDS = [
  "sound",
  "text",
  "animation",
  "transition",
  "component",
  "media",
  "template",
] as const;

export type LibraryKind = (typeof LIBRARY_KINDS)[number];

/** Where an item came from. Drives badges, and what deleting it means. */
export type LibrarySource =
  /** Ships in the app. Always available, never downloadable, never editable. */
  | "builtin"
  /** Saved by this user on this device (the old "Custom" tab). */
  | "user"
  /** Lives in THIS document — components, imported media. */
  | "project"
  /** In the online catalogue; bytes not fetched yet. */
  | "online"
  /** Was online; the bytes are on this device now. */
  | "downloaded";

export const LIBRARY_SOURCE_LABELS: Record<LibrarySource, string> = {
  builtin: "Built in",
  user: "Yours",
  project: "This project",
  online: "Library",
  downloaded: "Downloaded",
};

/* -------------------------------------------------------------------------- */
/* Previews                                                                    */
/* -------------------------------------------------------------------------- */

/**
 * What a card draws. Discriminated so a new preview medium is one arm plus one
 * branch in the card — and so a card can never be handed a URL it has no idea
 * how to show.
 */
export type LibraryPreview =
  /** Nothing to show; the card falls back to its kind's glyph. */
  | { type: "none" }
  /**
   * A quantised waveform (see `analyzeAudio`). This is what lets a sound that
   * has not been downloaded draw its REAL shape, at its real length, with its
   * hit marked — the one detail that makes an online sound card feel local.
   */
  | { type: "peaks"; peaks: number[]; durationMs: number; hitMs: number; loudnessDb: number | null }
  /** A still. Poster frames, cover art, icons. */
  | { type: "image"; url: string; width: number; height: number }
  /**
   * A silent looping clip played on hover, with a poster for the resting state.
   * The right medium for motion: a GIF is several times the bytes at a quarter
   * of the quality, and a still cannot show what a preset DOES.
   */
  | { type: "video"; url: string; posterUrl: string | null; width: number; height: number; durationMs: number }
  /**
   * The app draws it, from data it already has — local components, project
   * media, downloaded presets. Always preferred when available, because it is
   * never out of date.
   */
  | { type: "render" }
  /** A CSS keyframe approximation — the built-in text/animation gallery. */
  | { type: "css"; animation: string };

/* -------------------------------------------------------------------------- */
/* Actions                                                                     */
/* -------------------------------------------------------------------------- */

/**
 * What USING an item does. This is the whole contract between the browser and
 * the editor: the library never touches the document, it hands back one of
 * these and the surface applies it.
 *
 * A remote item has NO action until its bytes are local — `null` is precisely
 * the "download first" state, so the type makes the illegal case (using
 * something you do not have) unrepresentable rather than merely guarded.
 */
export type LibraryAction =
  /** A registered preset id, applied to the selection. */
  | { type: "preset"; domain: "text" | "animation" | "transition"; presetId: string }
  /** Clips captured as portable data — components, saved selections, packs. */
  | { type: "snapshot"; snapshot: LibrarySnapshot }
  /** A live component definition in THIS document: place an instance. */
  | { type: "instance"; frameId: string }
  /** A voice a sound layer can point at, and an audio clip you can drop. */
  | { type: "sound"; pack: SoundPackId | null; assetId: string | null; hitMs: number }
  /** An imported asset in this document: place it as a clip. */
  | { type: "asset"; assetId: string }
  /**
   * A whole project to start from (see `template.ts`): a built-in, built from
   * its script on first use. Using it makes a NEW project — it never edits the
   * open one.
   */
  | { type: "template"; templateId: string };

/* -------------------------------------------------------------------------- */
/* Remote                                                                      */
/* -------------------------------------------------------------------------- */

/** Where an online item's bytes live. Content-addressed, therefore immutable. */
export interface LibraryBlobRef {
  /** Path under the catalogue root, e.g. `blobs/<sha256>.wav`. */
  path: string;
  sha256: string;
  bytes: number;
  mime: string;
}

/** Who published an item. An id, never a name we would have to keep in sync. */
export interface PublisherRef {
  id: string;
  name: string;
}

/* -------------------------------------------------------------------------- */
/* The item                                                                    */
/* -------------------------------------------------------------------------- */

export interface LibraryItem {
  /**
   * Globally unique and STABLE across sessions and machines:
   * `<space>:<kind>:<localId>`. Stability is what lets stars, recents and
   * "already downloaded" survive a reload without a second index.
   */
  id: string;
  kind: LibraryKind;
  name: string;
  /** Lowercase, no `#`. Both the filter chips and `#hashtag` search read these. */
  tags: string[];
  /** One line, plain. Null when the name and the preview already say it. */
  blurb: string | null;
  source: LibrarySource;
  publisher: PublisherRef | null;
  preview: LibraryPreview;
  /**
   * The edit this hands the editor, or null while its bytes are still remote.
   * `resolveLibraryItem` is the one place that turns the second into the first.
   */
  action: LibraryAction | null;
  /** Set iff the item has bytes to fetch. Null for anything already usable. */
  blob: LibraryBlobRef | null;
  /** Pack this came from, in the online catalogue. Null otherwise. */
  packId: string | null;
  /**
   * The ONLINE item this local copy came from, if any.
   *
   * There is deliberately no separate "downloads" store: downloading an item
   * materialises it into the store its kind already has — a device sound, a
   * saved component, a project asset — and records where it came from here.
   * A second registry of downloaded things would be a second answer to "do I
   * have this", and the two would disagree the first time a user deleted one.
   * `mergeLibrary` reads this to fold the online card into the local one.
   */
  originId: string | null;
  /** Epoch ms. Null for built-ins, which have no meaningful date. */
  createdAt: number | null;
  /**
   * Where the publisher placed this on its shelf: low first. Editorial, from
   * `pack.json` — never derived from a date, so republishing an item does not
   * move it. Absent for the long tail, which sorts after, newest first.
   */
  order?: number;
}

/**
 * THE shelf order: placed items by `order`, then the rest newest first. One
 * comparator so Home, Explore and any agent listing agree on what comes first.
 */
export function compareShelfOrder(a: Pick<LibraryItem, "order" | "createdAt">, b: Pick<LibraryItem, "order" | "createdAt">): number {
  const ao = a.order ?? Number.POSITIVE_INFINITY;
  const bo = b.order ?? Number.POSITIVE_INFINITY;
  if (ao !== bo) return ao < bo ? -1 : 1;
  return (b.createdAt ?? 0) - (a.createdAt ?? 0);
}

/** Is this item usable right now, without a download? */
/**
 * The tag that says an item needs good hardware — a physics-heavy scene, a
 * black hole, a page of lit materials. A tag, not a field: the publisher (or
 * a template's `template.json`) already writes tags, and search finds it.
 */
export const HEAVY_TAG = "heavy";

/** Does this item warn that it may run slowly? */
export function isHeavyItem(item: Pick<LibraryItem, "tags">): boolean {
  return item.tags.includes(HEAVY_TAG);
}

export function isReady(item: LibraryItem): boolean {
  return item.action !== null;
}

/** Bytes a card should promise before this becomes usable (0 when ready). */
export function downloadBytes(item: LibraryItem): number {
  return item.action ? 0 : (item.blob?.bytes ?? 0);
}

/**
 * The item's stable id. An online item keeps the SAME id once downloaded, so
 * the browser shows one card that changed state rather than two that disagree.
 */
export function libraryItemId(space: string, kind: LibraryKind, localId: string): string {
  return `${space}:${kind}:${localId}`;
}

/**
 * WHAT this item actually points at, ignoring which provider produced it.
 *
 * Not the same question as `id`. An id says where a card came from — `device:`,
 * `project:`, `builtin:` — and two providers can legitimately answer for one
 * subject: adopting a device sound into a document makes the project's sound
 * provider list the very same asset, under a different prefix. The browser then
 * shows the card twice, which is what "a second identical sound appeared just
 * because I touched one" was.
 *
 * Keying on the subject is what makes that unrepresentable rather than merely
 * unlikely, and it holds for the seventh provider nobody has written yet.
 *
 * Kind is part of the key on purpose: one audio asset is legitimately a SOUND
 * on the sounds shelf and a MEDIA file on the media shelf. Those are two
 * browsable things, not one thing listed twice.
 */
export function librarySubjectKey(item: LibraryItem): string {
  const a = item.action;
  switch (a?.type) {
    case "sound":
      return `${item.kind}|sound|${a.pack ?? ""}|${a.assetId ?? ""}`;
    case "asset":
      return `${item.kind}|asset|${a.assetId}`;
    case "instance":
      return `${item.kind}|frame|${a.frameId}`;
    case "preset":
      return `${item.kind}|preset|${a.domain}|${a.presetId}`;
    case "template":
      return `${item.kind}|template|${a.templateId}`;
    // A snapshot is a copy, not a reference: two saved components with the same
    // clips are two things you can delete independently. Nothing to fold.
    default:
      return `${item.kind}|id|${item.id}`;
  }
}

/**
 * One card per subject, first provider wins.
 *
 * Order is the precedence, so `localLibrary` states it once by listing its
 * providers in the order it means: the device entry for a sound carries the hit
 * point and the published peaks, so it outranks the bare project asset that
 * appears the moment the sound is adopted.
 */
export function dedupeBySubject(items: LibraryItem[]): LibraryItem[] {
  const seen = new Set<string>();
  const out: LibraryItem[] = [];
  for (const item of items) {
    const key = librarySubjectKey(item);
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(item);
  }
  return out;
}
