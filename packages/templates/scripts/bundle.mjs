#!/usr/bin/env node
/**
 * Bundle every template folder into a TypeScript module the editor imports, so
 * built-in templates ship inside the app with no fetch. The folders stay the
 * source of truth — `template.json` (editorial facts), the build script and
 * the art it reads — and `--check` fails when the bundle is stale, so an art
 * or script edit cannot land without its bundle. (Same contract as
 * `@solomotion/skill`.)
 *
 * Each template becomes a `TemplateSource` (core `library/template.ts`): its
 * files keyed by their PROJECT path `<id>/<path>`, which is where they land in
 * the Scripts panel of a project made from it.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const TEXT = /\.(js|svg|json|md)$/;

const templates = [];
for (const id of readdirSync(root).sort()) {
  const dir = join(root, id);
  if (!statSync(dir).isDirectory()) continue;
  let meta;
  try {
    meta = JSON.parse(readFileSync(join(dir, "template.json"), "utf8"));
  } catch {
    continue;
  }
  const files = {};
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (TEXT.test(name) && name !== "template.json") files[`${id}/${relative(dir, p).split("\\").join("/")}`] = readFileSync(p, "utf8");
    }
  };
  walk(dir);
  const entry = `${id}/${meta.entry ?? "build.js"}`;
  if (!(entry in files)) throw new Error(`${id}: entry ${entry} is missing`);
  templates.push({ id, name: meta.name, blurb: meta.blurb ?? null, tags: meta.tags ?? [], version: meta.version ?? 1, entry, files });
}

const source = `// GENERATED by scripts/bundle.mjs from the template folders. Do not edit by hand.
export const BUILTIN_TEMPLATES: readonly {
  id: string;
  name: string;
  blurb: string | null;
  tags: string[];
  version: number;
  entry: string;
  files: Record<string, string>;
}[] = ${JSON.stringify(templates, null, 2)};
`;
const target = join(root, "src/bundle.generated.ts");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== source) {
    console.error("The templates bundle is stale. Run: pnpm --filter @solomotion/templates bundle");
    process.exit(1);
  }
  console.log(`templates bundle is current (${templates.length} templates)`);
} else {
  writeFileSync(target, source);
  console.log(`bundled ${templates.length} templates (${templates.map((t) => `${t.id}: ${Object.keys(t.files).length} files`).join(", ")})`);
}
