#!/usr/bin/env node
/**
 * Bundle the Markdown into a TypeScript module the editor can import, so the
 * skill ships inside the app with no fetch and no loader. The Markdown stays
 * the source of truth — it is what gets published — and `--check` fails when
 * the bundle is stale, so a skill edit cannot land without its bundle.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
// ONE skill version: the `version:` in SKILL.md's front matter — the number an
// agent reads, the one the MCP server's instructions tell it to watch, and the
// one this bundle exports as SKILL_VERSION. The package's own version is the
// npm release line (the public repo stamps every package with it), a different
// thing: it is never reported as the skill's (status once said "skill 1.53.0"
// to an agent reading 2.51.0).
const SKILL_MD = readFileSync(join(root, "skills/solomotion/SKILL.md"), "utf8");
const version = /^version:\s*(\S+)/m.exec(SKILL_MD)?.[1];
if (!version) {
  console.error("skills/solomotion/SKILL.md has no `version:` in its front matter.");
  process.exit(1);
}
const checking = process.argv.includes("--check");

function collect(dir) {
  const out = {};
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.(md|json)$/.test(name)) out[relative(dir, p).split("\\").join("/")] = readFileSync(p, "utf8");
    }
  };
  walk(dir);
  return out;
}

const skill = collect(join(root, "skills/solomotion"));
const design = collect(join(root, "design-systems/default"));
const source = `// GENERATED by scripts/bundle.mjs from skills/ and design-systems/. Do not edit by hand.
export const SKILL_VERSION = ${JSON.stringify(version)};
export const SKILL_FILES: Record<string, string> = ${JSON.stringify(skill, null, 2)};
export const DEFAULT_DESIGN_SYSTEM_FILES: Record<string, string> = ${JSON.stringify(design, null, 2)};
`;
const target = join(root, "src/bundle.generated.ts");
if (checking) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== source) {
    console.error("The skill bundle is stale. Run: pnpm --filter @solomotion/skill bundle");
    process.exit(1);
  }
  console.log(`skill bundle is current (${Object.keys(skill).length} skill files, ${Object.keys(design).length} design files)`);
} else {
  writeFileSync(target, source);
  console.log(`bundled ${Object.keys(skill).length} skill files, ${Object.keys(design).length} design files`);
}
